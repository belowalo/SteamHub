//! SteamTools configuration generation; input is data, never executable Lua.
use crate::{contracts::AppError, services::workspace::app_id};
use serde::Serialize;
use std::{
    collections::HashSet,
    fs::{self, OpenOptions},
    io::Write,
    path::Path,
};
fn invalid(s: &str) -> AppError {
    AppError::new("INVALID_INPUT", s, false)
}
#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct GeneratedLua {
    pub text: String,
    pub filename: String,
    pub installed_path: Option<String>,
    pub manifests: Vec<crate::services::manifest::CachedManifest>,
    pub warnings: Vec<String>,
}
/// Reads only InstalledDepots and matching DecryptionKey fields; never exports account tickets.
pub fn local_rows(root: &Path, manifest: &Path, app: &str) -> Result<(String, String), AppError> {
    use crate::services::library::keyvalues::{self as kv, Value};
    use std::io::Read;
    fn read(path: &Path) -> Result<Vec<(String, Value)>, AppError> {
        let mut text = String::new();
        fs::File::open(path)
            .and_then(|f| f.take(16 * 1024 * 1024 + 1).read_to_string(&mut text))
            .map_err(|_| invalid("Could not read local Steam depot metadata."))?;
        if text.len() > 16 * 1024 * 1024 {
            return Err(invalid("Local metadata exceeds 16 MiB."));
        }
        kv::parse(&text).map_err(|_| invalid("Invalid local Steam metadata."))
    }
    fn object<'a>(
        pairs: &'a [(String, Value)],
        name: &str,
    ) -> Result<&'a [(String, Value)], AppError> {
        kv::field(pairs, name)
            .ok()
            .flatten()
            .and_then(|v| v.object().ok())
            .ok_or_else(|| invalid("Local Steam depot metadata is incomplete."))
    }
    let acf = read(manifest)?;
    let state = object(&acf, "AppState")?;
    if kv::required(state, "appid").ok() != Some(app) {
        return Err(invalid("Installation AppID does not match."));
    }
    let installed = object(state, "InstalledDepots")?;
    let config = read(&root.join("config").join("config.vdf"))?;
    let depots = object(
        object(
            object(object(&config, "InstallConfigStore")?, "Software")?,
            "Valve",
        )?,
        "Steam",
    )?;
    let depots = object(depots, "depots")?;
    let mut rows = String::new();
    let mut dlcs = String::new();
    for (id, value) in installed {
        let depot = object(depots, id)?;
        let key = kv::required(depot, "DecryptionKey").map_err(|_| {
            invalid("A depot key is unavailable locally. Supply depot data manually.")
        })?;
        let info = value
            .object()
            .map_err(|_| invalid("Invalid installed depot."))?;
        let gid = kv::required(info, "manifest")
            .map_err(|_| invalid("Missing installed manifest GID."))?;
        rows.push_str(&format!("{id},{key},{gid}\n"));
        if let Some(dlc) = kv::field(info, "dlcappid")
            .ok()
            .flatten()
            .and_then(|v| v.text().ok())
        {
            dlcs.push_str(dlc);
            dlcs.push('\n');
        }
    }
    Ok((rows, dlcs))
}
pub fn generate(app: &str, rows: &str, dlcs: &str) -> Result<GeneratedLua, AppError> {
    let id = app_id(app)?.ok_or_else(|| invalid("Enter an AppID."))?;
    if rows.len() > 262144 || dlcs.len() > 32768 {
        return Err(invalid("Configuration is too large."));
    }
    let filename = format!("steamhub_{id}.lua");
    let mut text =
        format!("-- Generated by SteamHub; locally supplied depot keys.\naddappid({id})\n");
    let mut seen = HashSet::from([id]);
    for value in dlcs
        .split(|c: char| c.is_whitespace() || c == ',')
        .filter(|s| !s.is_empty())
    {
        let value = app_id(value)?.ok_or_else(|| invalid("Invalid DLC AppID."))?;
        if seen.insert(value.clone()) {
            text.push_str(&format!("addappid({value})\n"));
        }
    }
    let mut depots = HashSet::new();
    for line in rows.lines().filter(|l| !l.trim().is_empty()) {
        let f: Vec<_> = line
            .split(|c: char| c.is_whitespace() || c == ',')
            .filter(|s| !s.is_empty())
            .collect();
        if !(2..=3).contains(&f.len()) || depots.len() >= 1000 {
            return Err(invalid(
                "Use at most 1000 rows: depot ID, key, optional manifest GID.",
            ));
        }
        let depot = app_id(f[0])?.ok_or_else(|| invalid("Invalid depot ID."))?;
        if !depots.insert(depot.clone()) {
            return Err(invalid("Duplicate depot ID."));
        }
        if f[1].len() != 64 || !f[1].bytes().all(|c| c.is_ascii_hexdigit()) {
            return Err(invalid("Depot key must be 64 hexadecimal digits."));
        }
        text.push_str(&format!(
            "addappid({depot},1,\"{}\")\n",
            f[1].to_ascii_lowercase()
        ));
        if let Some(value) = f.get(2) {
            if !value.bytes().all(|c| c.is_ascii_digit()) {
                return Err(invalid("Manifest GID must be a positive uint64."));
            }
            let gid = value
                .parse::<u64>()
                .ok()
                .filter(|n| *n > 0)
                .ok_or_else(|| invalid("Manifest GID must be a positive uint64."))?;
            text.push_str(&format!("setManifestid({depot},\"{gid}\")\n"));
        }
    }
    if depots.is_empty() {
        return Err(invalid(
            "Supply at least one depot ID and key. Store listings cannot generate depot keys.",
        ));
    }
    Ok(GeneratedLua {
        text,
        filename,
        installed_path: None,
        manifests: vec![],
        warnings: vec![],
    })
}
pub fn runtime_root(root: &Path) -> Result<std::path::PathBuf, AppError> {
    let root = root
        .canonicalize()
        .map_err(|_| invalid("Choose your Steam installation folder."))?;
    if !root.join("steam.exe").is_file()
        || !((root.join("OpenSteamTool.dll").is_file()
            && (root.join("dwmapi.dll").is_file() || root.join("xinput1_4.dll").is_file()))
            || root.join("stbase.dll").is_file())
    {
        return Err(invalid(
            "SteamTools/OpenSteamTool runtime was not found in this Steam folder.",
        ));
    }
    Ok(root)
}
pub fn install(root: &Path, generated: &GeneratedLua) -> Result<String, AppError> {
    let io = |e: std::io::Error| {
        AppError::new(
            "IO_ERROR",
            &format!("Configuration install failed: {e}"),
            true,
        )
    };
    let root = runtime_root(root)?;
    if !root.join("steam.exe").is_file()
        || !((root.join("OpenSteamTool.dll").is_file()
            && (root.join("dwmapi.dll").is_file() || root.join("xinput1_4.dll").is_file()))
            || root.join("stbase.dll").is_file())
    {
        return Err(invalid(
            "Select a Steam folder containing an installed OpenSteamTool or SteamTools runtime.",
        ));
    }
    let mut directory = root.clone();
    for part in ["config", "lua"] {
        directory.push(part);
        if directory.exists() {
            if !directory.canonicalize().map_err(io)?.starts_with(&root) {
                return Err(invalid("Lua folder redirects outside Steam."));
            }
        } else {
            fs::create_dir(&directory).map_err(io)?;
        }
    }
    let target = directory.join(&generated.filename);
    if target.exists() {
        if fs::read(&target).map_err(io)? == generated.text.as_bytes() {
            return Ok(target.display().to_string());
        }
        return Err(AppError::new("CONFLICT", "A different Lua file exists at this destination. Preserve or back it up before replacing it.", false));
    }
    let temporary = directory.join(format!(
        ".{}.{}.tmp",
        generated.filename,
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos()
    ));
    let mut file = match OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&temporary)
    {
        Ok(f) => f,
        Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {
            if fs::read(&target).map_err(io)? == generated.text.as_bytes() {
                return Ok(target.display().to_string());
            }
            return Err(AppError::new("CONFLICT", "A different SteamHub Lua already exists for this AppID. Back it up before replacing it.", false));
        }
        Err(e) => return Err(io(e)),
    };
    if let Err(e) = file
        .write_all(generated.text.as_bytes())
        .and_then(|_| file.sync_all())
    {
        drop(file);
        let _ = fs::remove_file(&temporary);
        return Err(io(e));
    }
    drop(file);
    // Atomic publication with no overwrite: the runtime never sees a partial Lua file.
    let published = fs::hard_link(&temporary, &target);
    let _ = fs::remove_file(&temporary);
    published.map_err(io)?;
    Ok(target.display().to_string())
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn reads_local_keys_manifests_and_dlc_without_account_fields() {
        let dir = tempfile::tempdir().unwrap();
        fs::create_dir(dir.path().join("config")).unwrap();
        let key = "ab".repeat(32);
        fs::write(dir.path().join("config/config.vdf"), format!("\"InstallConfigStore\" {{ \"Software\" {{ \"Valve\" {{ \"Steam\" {{ \"depots\" {{ \"621\" {{ \"DecryptionKey\" \"{key}\" }} }} }} }} }} }}")).unwrap();
        let acf = dir.path().join("appmanifest_620.acf");
        fs::write(&acf, "\"AppState\" { \"appid\" \"620\" \"InstalledDepots\" { \"621\" { \"manifest\" \"18446744073709551615\" \"dlcappid\" \"622\" } } }").unwrap();
        let (rows, dlcs) = local_rows(dir.path(), &acf, "620").unwrap();
        let g = generate("620", &rows, &dlcs).unwrap();
        assert!(g.text.contains("addappid(622)"));
        assert!(g.text.contains("18446744073709551615"));
        assert!(local_rows(dir.path(), &acf, "999").is_err());
    }
    #[test]
    fn validates_data_and_preserves_uint64() {
        let key = "ab".repeat(32);
        let g = generate("620", &format!("621,{key},18446744073709551615"), "622,622").unwrap();
        assert!(g
            .text
            .contains("setManifestid(621,\"18446744073709551615\")"));
        assert_eq!(g.text.matches("addappid(622)").count(), 1);
        for bad in [
            format!("621,{key},18446744073709551616"),
            "621,os.execute('bad')".into(),
            format!("621,{key}\n621,{key}"),
        ] {
            assert!(generate("620", &bad, "").is_err());
        }
        assert!(generate("../620", &format!("621,{key}"), "").is_err());
    }
    #[test]
    fn preserves_existing_files_and_requires_runtime() {
        let dir = tempfile::tempdir().unwrap();
        fs::write(dir.path().join("steam.exe"), []).unwrap();
        let g = generate("620", &format!("621,{}", "ab".repeat(32)), "").unwrap();
        assert!(install(dir.path(), &g).is_err());
        fs::write(dir.path().join("OpenSteamTool.dll"), []).unwrap();
        fs::write(dir.path().join("dwmapi.dll"), []).unwrap();
        let target = install(dir.path(), &g).unwrap();
        assert_eq!(install(dir.path(), &g).unwrap(), target);
        fs::write(&target, "user content").unwrap();
        assert!(install(dir.path(), &g).is_err());
        assert_eq!(fs::read_to_string(target).unwrap(), "user content");
    }
}
